const PREFIX = 'little-loops-';
const SCOPE = self.registration.scope;
const INDEX_URL = new URL('index.html', SCOPE).href;
const MATCH = { ignoreSearch: true, ignoreVary: true };

const isMedia = (path) => path.includes('?v=');
const CORE = PRECACHE.filter((p) => !isMedia(p));
const MEDIA = PRECACHE.filter(isMedia);
const MEDIA_BUDGET_MS = 4 * 60 * 1000; // never hold an install longer than this for voice clips

self.addEventListener('install', (event) => {
  event.waitUntil((async () => {
    const cache = await caches.open(CACHE);
    await cache.addAll(CORE.map((path) => new Request(new URL(path, SCOPE).href, { cache: 'reload' })));
    await Promise.race([fillMedia(cache), new Promise((r) => setTimeout(r, MEDIA_BUDGET_MS))]);
  })());
});

/** Put every voice clip into `cache`: copied from an older version when unchanged, else downloaded. */
async function fillMedia(cache) {
  const older = [];
  for (const name of await caches.keys()) if (name.startsWith(PREFIX) && name !== CACHE) older.push(await caches.open(name));
  const todo = [];
  for (const path of MEDIA) {
    const url = new URL(path, SCOPE).href;
    if (await cache.match(url)) continue; // exact URL (incl. ?v=hash): already here
    todo.push(url);
  }
  let next = 0;
  const worker = async () => {
    while (next < todo.length) {
      const url = todo[next++];
      try {
        let res = null;
        for (const c of older) { res = await c.match(url); if (res) break; }
        if (!res) {
          const net = await fetch(new Request(url, { cache: 'reload' }));
          if (net.status === 200 && net.type === 'basic') res = net;
        }
        if (res) await cache.put(url, res);
      } catch { /* offline or quota: the device voice covers it; TOPUP retries later */ }
    }
  };
  await Promise.all(Array.from({ length: 6 }, worker));
}

self.addEventListener('activate', (event) => {
  event.waitUntil((async () => {
    // Remove old versions of THIS app. Only entries under our scope are touched, so another copy of
    // Little Loops at a different path on the same origin (e.g. a /little-loops-beta/ deploy) is safe.
    for (const name of await caches.keys()) {
      if (!name.startsWith(PREFIX) || name === CACHE) continue;
      const old = await caches.open(name);
      const keys = await old.keys();
      const ours = keys.filter((req) => req.url.startsWith(SCOPE));
      if (ours.length === keys.length) await caches.delete(name);
      else await Promise.all(ours.map((req) => old.delete(req)));
    }
    await self.clients.claim();
  })());
});

self.addEventListener('message', (event) => {
  if (event.data && event.data.type === 'SKIP_WAITING') self.skipWaiting();
  // The page asks (once per start) to download any voice clips a flaky install missed.
  if (event.data && event.data.type === 'TOPUP') event.waitUntil(caches.open(CACHE).then(fillMedia).catch(() => {}));
});

self.addEventListener('fetch', (event) => {
  const req = event.request;
  if (req.method !== 'GET') return;
  if (!req.url.startsWith(SCOPE)) return; // cross-origin, or outside our sub-path: browser default
  if (req.cache === 'only-if-cached' && req.mode !== 'same-origin') return;
  if (req.headers.has('range')) {
    // <audio> asks for byte ranges. Serve them from the cache (offline voice); otherwise let the
    // browser go to the network as usual.
    event.respondWith(rangeFromCache(req));
    return;
  }

  if (req.mode === 'navigate' && isAppPage(req.url)) {
    event.respondWith(appShell(req));
  } else {
    event.respondWith(cacheFirst(req, event));
  }
});

/** A 206 slice of the cached file for a Range request; the network if it isn't cached. */
async function rangeFromCache(req) {
  const cache = await caches.open(CACHE);
  const hit = await cache.match(req.url, MATCH);
  if (!hit) {
    try { return await fetch(req); } catch { return Response.error(); }
  }
  const buf = await hit.arrayBuffer();
  const size = buf.byteLength;
  const m = /^bytes=(\d*)-(\d*)$/.exec((req.headers.get('range') || '').trim());
  let start = 0;
  let end = size - 1;
  if (m && m[1] !== '') {
    start = Number(m[1]);
    if (m[2] !== '') end = Math.min(Number(m[2]), size - 1);
  } else if (m && m[2] !== '') {
    start = Math.max(0, size - Number(m[2])); // suffix range: the last N bytes
  }
  if (!m || start > end || start >= size) {
    return new Response(null, { status: 416, headers: { 'Content-Range': `bytes */${size}` } });
  }
  const headers = new Headers(hit.headers);
  headers.set('Content-Range', `bytes ${start}-${end}/${size}`);
  headers.set('Content-Length', String(end - start + 1));
  headers.set('Accept-Ranges', 'bytes');
  return new Response(buf.slice(start, end + 1), { status: 206, statusText: 'Partial Content', headers });
}

/** The scope root or index.html, ignoring ?query and #hash. */
function isAppPage(url) {
  const u = new URL(url);
  u.search = '';
  u.hash = '';
  return u.href === SCOPE || u.href === INDEX_URL;
}

async function appShell(req) {
  const cache = await caches.open(CACHE);
  const hit = (await cache.match(INDEX_URL, MATCH)) || (await cache.match(SCOPE, MATCH));
  if (hit) return navigable(hit);
  try {
    return await fetch(req);
  } catch {
    return Response.error();
  }
}

async function cacheFirst(req, event) {
  const cache = await caches.open(CACHE);
  const hit = await cache.match(req, MATCH);
  if (hit) return req.mode === 'navigate' ? navigable(hit) : hit;
  let res;
  try {
    res = await fetch(req);
  } catch {
    return Response.error(); // offline and not cached
  }
  if (res.status === 200 && res.type === 'basic') {
    event.waitUntil(cache.put(req, res.clone()).catch(() => { /* quota or opaque: skip */ }));
  }
  return res;
}

/**
 * Browsers refuse a redirected response for a navigation. Hosts that redirect index.html -> ./
 * (some do) would leave a redirected copy in the cache, so re-wrap it as a plain response.
 */
async function navigable(res) {
  if (!res.redirected) return res;
  const body = await res.blob();
  return new Response(body, { status: res.status, statusText: res.statusText, headers: res.headers });
}
